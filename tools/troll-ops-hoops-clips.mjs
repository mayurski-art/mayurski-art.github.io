// Troll Forces, Troll Beach 5d: the court clips into Roblox Studio and back.
//
//   node tools/troll-ops-hoops-clips.mjs luau [names...] > clips.luau
//     The Luau that builds each clip of tools/troll-ops-hoops-poses.mjs as a
//     KeyframeSequence on workspace.TF_Rig (AnimSaves/TF_<Name>, nested the
//     rig's Motor6D way so Studio's Animation Editor plays it, TF_Meta, the
//     markers), then sends each to tools/troll-ops-roblox-anim.mjs serve,
//     retrying till a server is up (the server takes one POST and exits, so
//     run it once per clip: the "export" mode below does).
//   node tools/troll-ops-hoops-clips.mjs export [names...]
//     Runs serve once per clip, in order, so the Luau's sends land; the clips
//     are written to characters/clips/<name>.json by the exporter.

import { spawnSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CLIPS } from "./troll-ops-hoops-poses.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const [mode = "luau", ...pick] = process.argv.slice(2);
const names = (pick.length ? pick : Object.keys(CLIPS)).filter((n) => n !== "probe");
const EASE = { linear: ["Linear", "In"], constant: ["Constant", "In"], in: ["Cubic", "In"], out: ["Cubic", "Out"], inout: ["Cubic", "InOut"] };
const seqName = (n) => "TF_" + n.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join("");

if (mode === "export") {
  for (const n of names) {
    const r = spawnSync(process.execPath, [path.join(ROOT, "tools/troll-ops-roblox-anim.mjs"), "serve"], { stdio: "inherit" });
    if (r.status) process.exit(r.status);
    console.log(`exported ${n}`);
  }
  process.exit(0);
}

const lua = (v) => (Array.isArray(v) ? `{${v.map(lua).join(",")}}` : typeof v === "string" ? JSON.stringify(v) : typeof v === "boolean" ? String(v) : String(+(+v).toFixed(5)));
const clips = names.map((n) => {
  const C = CLIPS[n];
  const joints = new Set();
  for (const k of C.keys) for (const j in k.pose) joints.add(j);
  const keys = C.keys.map((k) => {
    const [style, dir] = EASE[k.ease || "inout"];
    const poses = [...joints].map((j) => {
      const v = k.pose[j];
      const r = !v ? [0, 0, 0] : Array.isArray(v) ? v : v.r || [0, 0, 0];
      const p = v && !Array.isArray(v) && v.p ? v.p : [0, 0, 0];
      return `{${lua(j)},${lua(r)},${lua(p)}}`;
    });
    return `{t=${lua(k.t)},style=${lua(style)},dir=${lua(dir)},markers=${lua(k.markers || [])},poses={${poses.join(",")}}}`;
  });
  return `{seq=${lua(seqName(n))},clip=${lua(n)},loop=${lua(!!C.loop)},length=${lua(C.length)},meta=${lua(C.meta || "")},keys={${keys.join(",")}}}`;
});

console.log(`-- generated by tools/troll-ops-hoops-clips.mjs (Troll Beach 5d court clips)
local CLIPS = {${clips.join(",\n")}}
local PORT, K = 5299, 4
local HttpService = game:GetService("HttpService")
local rig = workspace:FindFirstChild("TF_Rig")
assert(rig, "no workspace.TF_Rig")
local saves = rig:FindFirstChild("AnimSaves") or Instance.new("Model")
saves.Name = "AnimSaves"; saves.Parent = rig
-- the joint tree: a pose's parent is the pose of its Motor6D's Part0
local parentOf = {}
for _, m in ipairs(rig:GetDescendants()) do
	if m:IsA("Motor6D") and m.Part0 and m.Part1 then parentOf[m.Part1.Name] = m.Part0.Name end
end
local function build(c)
	local old = saves:FindFirstChild(c.seq); if old then old:Destroy() end
	local kfs = Instance.new("KeyframeSequence"); kfs.Name = c.seq; kfs.Loop = c.loop
	local meta = Instance.new("StringValue"); meta.Name = "TF_Meta"; meta.Value = c.meta; meta.Parent = kfs
	for _, k in ipairs(c.keys) do
		local kf = Instance.new("Keyframe"); kf.Time = k.t
		local poses = {}
		local function poseFor(name)
			if poses[name] then return poses[name] end
			local p = Instance.new("Pose"); p.Name = name; p.Weight = 0
			poses[name] = p
			local up = parentOf[name]
			p.Parent = up and poseFor(up) or kf
			return p
		end
		for _, j in ipairs(k.poses) do
			local p = poseFor(j[1])
			local r, s = j[2], j[3]
			p.CFrame = CFrame.new(s[1] * K, s[2] * K, s[3] * K) * CFrame.Angles(math.rad(r[1]), math.rad(r[2]), math.rad(r[3]))
			p.Weight = 1
			p.EasingStyle = Enum.PoseEasingStyle[k.style]; p.EasingDirection = Enum.PoseEasingDirection[k.dir]
		end
		for _, m in ipairs(k.markers) do local mk = Instance.new("KeyframeMarker"); mk.Name = m; kf:AddMarker(mk) end
		kf.Parent = kfs
	end
	kfs.Parent = saves
	return kfs
end
local function send(c, kfs)
	local keys = kfs:GetKeyframes()
	table.sort(keys, function(a, b) return a.Time < b.Time end)
	local out = {}
	for _, kf in ipairs(keys) do
		local poses, markers = {}, {}
		for _, d in ipairs(kf:GetDescendants()) do
			if d:IsA("Pose") and d.Weight > 0 then
				poses[d.Name] = { cf = { d.CFrame:GetComponents() }, w = d.Weight, ease = d.EasingStyle.Name, dir = d.EasingDirection.Name }
			end
		end
		for _, mk in ipairs(kf:GetMarkers()) do table.insert(markers, mk.Name) end
		table.insert(out, { t = kf.Time, poses = poses, markers = markers })
	end
	local body = HttpService:JSONEncode({ name = c.clip, source = c.seq, K = K, loop = kfs.Loop, length = c.length, meta = c.meta, keyframes = out })
	for _ = 1, 120 do
		local ok, res = pcall(function()
			return HttpService:RequestAsync({ Url = "http://127.0.0.1:" .. PORT .. "/anim", Method = "POST",
				Headers = { ["Content-Type"] = "application/json" }, Body = body })
		end)
		if ok and res.Success then return res.StatusCode end
		task.wait(0.5)
	end
	error("no export server for " .. c.clip)
end
local was = HttpService.HttpEnabled
HttpService.HttpEnabled = true
local done = {}
for _, c in ipairs(CLIPS) do
	local kfs = build(c)
	task.wait()
	send(c, kfs)
	table.insert(done, c.clip)
	task.wait(0.8)   -- the next server comes up
end
HttpService.HttpEnabled = was
return "built and sent: " .. table.concat(done, ", ")`);
