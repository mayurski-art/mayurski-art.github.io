// Write FACIALS / Gold Tooth: traits/src/facial-gold-tooth.svg, the whole
// of one upper tooth of the trollface art filled in gold (user, 2026-10-16:
// "fix 2631 in terms of filling that golden tooth"; it was a small square on
// the wrong tooth). The tooth's own shape is flood-filled out of trollface
// transparent.png from a seed inside it, so the gold meets the art's black
// lines all round. TROLLS #2631's gold tooth is the third upper tooth from
// the left as the NFT draws the face; the game flips the NFT head
// (blocky-body.js HEAD.mirror), so in the art it's the big one under the
// nose (seed below).
//
//   NODE_PATH=<checkout>/node_modules node tools/troll-ops-gold-tooth-art.mjs
//   node tools/troll-ops-bake-traits.mjs --only facial-gold-tooth
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FACE = join(ROOT, "assets/images/wallpaper/trollface transparent.png");
const OUT = join(ROOT, "assets/games/troll-ops/traits/src/facial-gold-tooth.svg");
// and the trollface with it painted in (what the NFT body wears, character.js
// FACE_ART: as a card in front of the face, the grin's sculpted bulge hid
// most of it)
const FACE_OUT = join(ROOT, "assets/games/troll-ops/traits/src/face-gold-tooth.svg");
const SEED = [405, 420];   // inside the tooth, in the face art's pixels
const GROW = 2;            // px past the white, under the art's lines (no white seam)

const browser = await chromium.launch();
const page = await browser.newPage();
const rows = await page.evaluate(async ({ png, SEED, GROW }) => {
  const img = new Image(); img.src = "data:image/png;base64," + png; await img.decode();
  const W = img.width, H = img.height, c = document.createElement("canvas"); c.width = W; c.height = H;
  const g = c.getContext("2d"); g.drawImage(img, 0, 0);
  const d = g.getImageData(0, 0, W, H).data;
  const white = (k) => d[k * 4 + 3] > 128 && d[k * 4] + d[k * 4 + 1] + d[k * 4 + 2] > 450;
  const seen = new Uint8Array(W * H), st = [SEED[1] * W + SEED[0]];
  seen[st[0]] = 1;
  const span = new Map();   // y -> [x0, x1]
  while (st.length) {
    const k = st.pop(), x = k % W, y = (k / W) | 0;
    const s = span.get(y) || [x, x]; s[0] = Math.min(s[0], x); s[1] = Math.max(s[1], x); span.set(y, s);
    for (const q of [k - 1, k + 1, k - W, k + W]) if (!seen[q] && white(q)) { seen[q] = 1; st.push(q); }
  }
  return [...span.entries()].sort((a, b) => a[0] - b[0]).map(([y, [x0, x1]]) => [y, x0 - GROW, x1 + GROW]);
}, { png: readFileSync(FACE).toString("base64"), SEED, GROW });
await browser.close();

// face art px -> head frame (the face at 100, 233.3, 800 x 750)
const fx = (x) => 100 + x, fy = (y) => 233.3 + y * 750 / 730;
const f = (v) => Math.round(v * 10) / 10;
const top = rows[0][0] - GROW, bot = rows.at(-1)[0] + GROW;
const pts = [[rows[0][1], top], ...rows.map(([y, x0]) => [x0, y]), [rows.at(-1)[1], bot], [rows.at(-1)[2], bot],
  ...rows.slice().reverse().map(([y, , x1]) => [x1, y]), [rows[0][2], top]]
  .filter((_, i, a) => i % 3 === 0 || i === a.length - 1);
const d = "M" + pts.map(([x, y]) => `${f(fx(x))} ${f(fy(y))}`).join(" L") + " Z";
const [X0, X1] = [Math.min(...rows.map((r) => r[1])), Math.max(...rows.map((r) => r[2]))];
const Y0 = fy(top), Y1 = fy(bot), mid = (Y0 + Y1) / 2;

writeFileSync(OUT, `<!--
  TROLLS trait: FACIALS / Gold Tooth. GENERATED by
  tools/troll-ops-gold-tooth-art.mjs (edit it there): one whole upper tooth
  of the trollface art, flood-filled from the art itself, capped in gold
  with a darker lower half and a glint. TROLLS #2631's: the third upper
  tooth from the left as the NFT draws it (the game flips the head).
  Frame: the head-trait frame (traits/README.md).
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1033" width="1000" height="1033">
  <defs>
    <clipPath id="tooth"><path d="${d}"/></clipPath>
    <linearGradient id="gold" x1="0" y1="${f(Y0)}" x2="0" y2="${f(Y1)}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#f7d34e"/><stop offset="0.55" stop-color="#e8b42a"/><stop offset="1" stop-color="#c38d16"/>
    </linearGradient>
  </defs>
  <g clip-path="url(#tooth)">
    <rect x="${f(fx(X0))}" y="${f(Y0)}" width="${f(X1 - X0)}" height="${f(Y1 - Y0)}" fill="url(#gold)"/>
    <!-- a glint across the top -->
    <path fill="none" stroke="#fff3b4" stroke-width="6" stroke-linecap="round" d="M${f(fx(X0) + (X1 - X0) * 0.22)} ${f(Y0 + (mid - Y0) * 0.55)} L${f(fx(X0) + (X1 - X0) * 0.55)} ${f(Y0 + (mid - Y0) * 0.45)}"/>
  </g>
</svg>
`);
// the same tooth in the face art's own frame (800 x 730)
const dF = "M" + pts.map(([x, y]) => `${f(x)} ${f(y)}`).join(" L") + " Z";
writeFileSync(FACE_OUT, `<!--
  TROLLS #2631's face (FACIALS / Gold Tooth): the trollface with one upper
  tooth filled in gold. GENERATED by tools/troll-ops-gold-tooth-art.mjs.
  In the trollface png's frame (800 x 730), so it swaps in for the face.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 730" width="800" height="730">
  <defs>
    <clipPath id="tooth"><path d="${dF}"/></clipPath>
    <linearGradient id="gold" x1="0" y1="${top}" x2="0" y2="${bot}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#f7d34e"/><stop offset="0.55" stop-color="#e8b42a"/><stop offset="1" stop-color="#c38d16"/>
    </linearGradient>
  </defs>
  <image href="../../../../images/wallpaper/trollface%20transparent.png" width="800" height="730"/>
  <g clip-path="url(#tooth)">
    <rect x="${X0}" y="${top}" width="${X1 - X0}" height="${bot - top}" fill="url(#gold)"/>
    <path fill="none" stroke="#fff3b4" stroke-width="6" stroke-linecap="round" d="M${f(X0 + (X1 - X0) * 0.22)} ${f(top + (bot - top) * 0.28)} L${f(X0 + (X1 - X0) * 0.55)} ${f(top + (bot - top) * 0.22)}"/>
  </g>
  <!-- the art's own lines back over the gold's edge -->
  <image href="../../../../images/wallpaper/trollface%20transparent.png" width="800" height="730" clip-path="url(#tooth)" style="mix-blend-mode:multiply"/>
</svg>
`);
console.log("wrote", OUT, FACE_OUT, rows.length, "rows");
